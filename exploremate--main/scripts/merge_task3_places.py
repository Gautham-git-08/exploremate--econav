def merge_places():
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)

    existing_places = data.get("places", [])
    existing_by_id = {p["id"]: p for p in existing_places}
    existing_names_lower = {p["name"].lower(): p["id"] for p in existing_places}

    # Update or add missing fields
    added_count = 0
    updated_count = 0

    for new_p in NEW_ENTRIES:
        # Match by ID or name
        matched_id = None
        if new_p["id"] in existing_by_id:
            matched_id = new_p["id"]
        elif new_p["name"].lower() in existing_names_lower:
            matched_id = existing_names_lower[new_p["name"].lower()]

        if matched_id:
            # Merge fields without overwriting verified images or custom fields
            target = existing_by_id[matched_id]
            for k, v in new_p.items():
                if k not in target or target[k] is None or target[k] == "":
                    target[k] = v
            updated_count += 1
        else:
            existing_places.append(new_p)
            existing_by_id[new_p["id"]] = new_p
            existing_names_lower[new_p["name"].lower()] = new_p["id"]
            added_count += 1

    # Ensure all existing places have the required fields
    for p in existing_places:
        if "aliases" not in p:
            p["aliases"] = []
        if "category" not in p:
            p["category"] = "French heritage & landmarks" if "french" in p["id"] else "Spiritual & religious"
        if "shortDescription" not in p:
            p["shortDescription"] = p.get("review_summary", p.get("description", ""))[:160]
        if "longDescription" not in p:
            p["longDescription"] = p.get("description", p.get("review_summary", ""))
        if "whatToExperience" not in p:
            p["whatToExperience"] = ["Heritage architecture", "Quiet contemplation", "Local sightseeing"]
        if "durationMin" not in p:
            p["durationMin"] = 45
        if "accessNote" not in p:
            p["accessNote"] = "Open during regular operating hours."
        if "outOfCityCentre" not in p:
            p["outOfCityCentre"] = False
        if "lat" in p and "lng" not in p and "long" in p:
            p["lng"] = p["long"]

    data["places"] = existing_places

    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    print(f"Merge complete: {added_count} places added, {updated_count} existing places enhanced.")
    print(f"Total places in database: {len(existing_places)}")

if __name__ == "__main__":
    merge_places()
